function SelectTrigger({
  className,
  size = "default",
  children,
  ...props
}: SelectPrimitive.Trigger.Props & {
  size?: "sm" | "default"
}) {
  return (
    <SelectPrimitive.Trigger
      data-slot="select-trigger"
      data-size={size}
      className={cn(
        // Layout
        "flex w-full items-center justify-between gap-2 rounded-lg border text-sm whitespace-nowrap outline-none select-none",
        // Colors
        "border-input bg-card text-foreground hover:bg-muted/50 transition-colors",
        // Focus
        "focus-visible:border-ring focus-visible:ring-2 focus-visible:ring-ring/30",
        // Disabled
        "disabled:cursor-not-allowed disabled:opacity-50",
        // Placeholder
        "data-placeholder:text-muted-foreground",
        // Sizes
        "data-[size=default]:h-9 data-[size=default]:px-3 data-[size=default]:py-2",
        "data-[size=sm]:h-7 data-[size=sm]:px-2.5 data-[size=sm]:py-1 data-[size=sm]:text-xs data-[size=sm]:rounded-md",
        // Value styling
        "*:data-[slot=select-value]:line-clamp-1 *:data-[slot=select-value]:flex *:data-[slot=select-value]:items-center *:data-[slot=select-value]:gap-1.5",
        // Icon sizing
        "[&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
        className
      )}
      {...props}
    >
      {children}
      <SelectPrimitive.Icon
        render={
          <ChevronDownIcon className="size-4 text-muted-foreground/70 shrink-0 transition-transform [[data-popup-open]_&]:rotate-180" />
        }
      />
    </SelectPrimitive.Trigger>
  )
}

function SelectContent({
  className,
  children,
  side = "bottom",
  sideOffset = 4,
  align = "center",
  alignOffset = 0,
  alignItemWithTrigger = true,
  ...props
}: SelectPrimitive.Popup.Props &
  Pick<
    SelectPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset" | "alignItemWithTrigger"
  >) {
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Positioner
        side={side}
        sideOffset={sideOffset}
        align={align}
        alignOffset={alignOffset}
        alignItemWithTrigger={alignItemWithTrigger}
        className="isolate z-50"
      >
        <SelectPrimitive.Popup
          data-slot="select-content"
          data-align-trigger={alignItemWithTrigger}
          className={cn(
            // Layout
            "relative isolate z-50 max-h-(--available-height) w-(--anchor-width) min-w-[180px] origin-(--transform-origin) overflow-x-hidden overflow-y-auto",
            // Style
            "rounded-xl bg-popover text-popover-foreground p-1",
            "shadow-lg ring-1 ring-border/50",
            // Animation
            "duration-150 data-[align-trigger=true]:animate-none",
            "data-[side=bottom]:slide-in-from-top-2 data-[side=top]:slide-in-from-bottom-2",
            "data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95",
            "data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95",
            className
          )}
          {...props}
        >
          <SelectScrollUpButton />
          <SelectPrimitive.List>{children}</SelectPrimitive.List>
          <SelectScrollDownButton />
        </SelectPrimitive.Popup>
      </SelectPrimitive.Positioner>
    </SelectPrimitive.Portal>
  )
}

